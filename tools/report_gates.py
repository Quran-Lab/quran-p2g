"""gates/*.json -> docs/GATES.md (every number in the README comes from these files).

    python -X utf8 tools/report_gates.py
"""
from __future__ import annotations

import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def load(name):
    p = os.path.join(ROOT, "gates", name)
    return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else None


def pct(a, b):
    return f"{100 * a / b:.2f} %" if b else "n/a"


def main():
    g1, g3, g4, mu = load("g1.json"), load("g3.json"), load("g4.json"), load("muaalem.json")
    g2 = {f: load(f"g2_{f}.json") for f in ("tj3g", "tj3")}
    L = ["# Verification gates", "",
         "Generated by `tools/report_gates.py` from `gates/*.json`; each gate's script is in `tools/`.", "",
         "## Changes since 0.1.0", "",
         "Every 0.1.0 G2 miss and G3 disagreement was put in one class: an attribution tie (a), a convention "
         "difference with the benchmark scorer (b), or a bug (c). The bugs are fixed (DESIGN.md sections 5 and 7); the "
         "ties and conventions are measured as described below, with the strict numbers kept.", "",
         "| number | 0.1.0 | 0.1.1 strict | 0.1.1 with ties / conventions |", "|---|---|---|---|",
         "| G2 exact, tj3g | 99.87 % | 99.95 % | 100.00 % |",
         "| G2 exact, tj3 | 99.75 % | 99.92 % | 100.00 % |",
         "| G2 read-back, tj3g | 98.71 % | 98.88 % | 100.00 % (named rules) |",
         "| G2 read-back, tj3 | 98.38 % | 98.58 % | 100.00 % (named rules) |",
         "| G3 word flags vs scorer, V4 / v3.1 test | 99.94 / 99.86 % | 99.94 / 99.86 % | 100.00 / 100.00 % |",
         "| G4 exact ayah, canonical | 97.07 % | 97.07 % (the ceiling) | 100.00 % up to identical text |", "",
         "0.1.0 G2 misses: 93 (32 tj3g, 61 tj3): 63 were (c), a skip or repeat explained as a stop plus a word "
         "fragment, fixed in the aligner; 30 are (a), identical phone strings. 0.1.0 read-back differences: 491; "
         "after the speller and gate fixes every one left is forced by a named reading rule. G3: no (c); every "
         "disagreement is (b) or (a).", "",
         "0.1.2 (DESIGN.md, last section): a word re-split after the alignment, so one wrong word is one word error "
         "(a symmetric test had a replaced word cost 18.11 % WER through the phones against 14.57 % as text), and three "
         "tajweed-level rules narrowed to where they apply (they hid a few real letter mistakes). Gate G5 is new. "
         "G2 stays at 100.00 % up to an equivalent attribution; its strict number moves to 99.79 % (tj3g) and 99.78 % "
         "(tj3) because the re-split can put an edit on a neighbouring word that gives the identical phones. G3 WER "
         "falls (the double charge is gone) while its word flags still agree with the benchmark's scorer.", "",
         "0.1.3: extra speech (a word not in the ayah, a glued repeat) is written as words of its own; G5 adds several "
         "mistakes together (0.1.2 charged three adjacent mistakes 30.65 % through the phones against 33.63 % as text; "
         "0.1.3: 17.33 % against 17.14 % on the G5 set).", ""]
    if g1:
        L += ["## G1 round trip (quran-g2p phones -> quran-p2g -> mushaf text)", "",
              "Inputs come from quran-g2p itself (a fresh single-ayah lattice per ayah, `phonemize`, "
              "`phonemize_concat`), never from the packaged artifact. Pass = every word a match, no insertion, "
              "Uthmani and imla'i text identical to the mushaf.", "",
              "| check | result |", "|---|---|",
              f"| ayat with every path passing | {g1['ayat_all_paths_pass']:,} / {g1['ayat']:,} |",
              f"| single-ayah paths (stop patterns none / all / even / odd x sukun / rawm / ishmam x base / "
              f"alternate wajh, in tj3, tj3g, units; duplicates removed) | {g1['single_ayah_paths']:,}, "
              f"{g1['single_ayah_path_failures']} failures |",
              f"| lattice canonical path equals quran-g2p `phonemize` | {g1['lattice_canonical_equals_phonemize']:,}"
              f" / {g1['ayat']:,} |",
              f"| runs of up to 4 ayat read in wasl across the ayah ends | {g1['range_paths']:,} paths |",
              f"| basmala read in wasl before ayah 1 (112 surahs x 3 formats) | {g1['basmala_paths']:,} paths |",
              f"| range and basmala failures | {g1['range_and_basmala_failures']} |", ""]
    rule_text = {
        "long_vowel_before_cluster": "a word-final long vowel is shortened before a word that starts with a cluster "
                                     "(wasl); read again with a stop after the word, the spelling gives the long vowel",
        "waqf_final_short_vowel": "the last word of the ayah is read before a stop, where a final short vowel is not "
                                  "said; read again in wasl into the next ayah, the spelling gives the planted vowel",
        "allah_madd": "the madd of the name of Allah is read long whatever is written",
        "idgham_mithlayn": "a sakin consonant before the same consonant merges with it into one held consonant "
                           "(inside the word or across the boundary)",
        "ikhfa_before_non_ikhfa": "the ikhfa nasal exists only before the 15 ikhfa letters; a bare noon before any "
                                  "other letter is read by that letter's noon rule",
    }
    for f, g in g2.items():
        if not g:
            continue
        L += [f"## G2 planted single edits ({f})", "",
              f"{g['planted_cases']:,} cases, 4 per ayah over all 6,236 ayat (an ayah with no eligible site for "
              f"an edit type skips it: {g['skipped_no_site']}).", "",
              "- **Exact (strict)**: quran-p2g reports exactly the planted statuses (the edited word deviant, or "
              "deleted, or one inserted repeat of it; every other word a match).",
              "- **Exact (equivalent attribution)**: the output is the planted statuses of another attribution that "
              "is proven equally valid: the same edit on another word gives the identical phone string "
              "(`tools/g2_equiv.py`). Example: skipping either of the two words of هَيْهَاتَ هَيْهَاتَ, or a "
              "consonant + vowel inserted next to an identical consonant + vowel at a word boundary. Nothing else "
              "is accepted.",
              "- Precision / recall over flagged units (words, plus the inserted repeat), strict / equivalent.",
              "- **Read-back**: quran-g2p reads the ayah with the spelled word in place (same neighbours, ibtida at "
              "the start, wasl inside, waqf at the end, as planted) and must return the planted tokens for that "
              "word. A difference that a named reading rule forces whatever is written is listed by rule below.", "",
              "| edit | cases | exact strict | exact equivalent | precision | recall | read-back equal | "
              "read-back equal or named rule |", "|---|---|---|---|---|---|---|---|"]
        order = ["vowel_swap", "consonant_swap", "long_short", "shadda_drop", "word_skip", "word_repeat",
                 "inserted_syllable", "ALL"]
        for t in order:
            if t not in g["by_type"]:
                continue
            v = g["by_type"][t]
            if "readback_cases" in v:
                rb = f"{v['readback_equal_pct']:.2f} % of {v['readback_cases']:,}"
                rb2 = f"{v['readback_equal_or_rule_pct']:.2f} %"
            else:
                rb = rb2 = "n/a"
            name = "**all**" if t == "ALL" else t
            pr = f"{v['precision']:.2f} / {v['precision_equiv']:.2f} %"
            rc = f"{v['recall']:.2f} / {v['recall_equiv']:.2f} %"
            L.append(f"| {name} | {v['cases']:,} | {v['exact_pct']:.2f} % | {v['exact_equiv_pct']:.2f} % | {pr} | "
                     f"{rc} | {rb} | {rb2} |")
        a = g["by_type"]["ALL"]
        L += ["", f"Equivalent attributions: {a['equiv_same_string']} cases (identical phone string), "
              f"{a['equiv_equal_cost']} by equal cost only. Strict misses by edit type: " +
              ", ".join(f"{t} {g['by_type'][t]['cases'] - g['by_type'][t]['exact']}" for t in order[:-1]
                        if t in g["by_type"] and g["by_type"][t]["cases"] != g["by_type"][t]["exact"]) + ".", ""]
        rules = a.get("readback_rules", {})
        L += ["Read-back differences by rule (each one checked mechanically; see `tools/gate_g2.py`):", "",
              "| rule | words | what it is |", "|---|---|---|"]
        for k, n in sorted(rules.items(), key=lambda x: -x[1]):
            L.append(f"| `{k}` | {n} | {rule_text.get(k, '')} |")
        if a.get("readback_equal_without_reference"):
            L.append(f"| `equal_without_reference` | {a['readback_equal_without_reference']} | quran-g2p refuses a "
                     "spelling at a word its ayah reference pins (a muqatta'at letter name, the tasheel of 41:44); "
                     "read without the reference it gives the planted tokens |")
        left = a["readback_cases"] - a["readback_equal_or_rule"]
        L += ["", f"Read-back cases left unexplained: {left}; refused by the engine: {a['readback_engine_refused']}."
              , ""]
    if g3:
        L += ["## G3 real model output (V4 benchmark, public correct tiers)", "",
              "TajweedFormer V4 (AGG 18k) and zipformer v3.1 tj3 hypotheses on the public correct tiers of the V4 "
              "benchmark (professional reciters, held-out panel). WER: corpus level, undiacritized against the "
              "imla'i text with the board normalisation, diacritized against the Uthmani text.", "",
              "Word-flag agreement, per Uthmani word, flagged (not a match) by quran-p2g vs flagged by the benchmark "
              "scorer's `tj3_word_flags` on the same hypotheses:", "",
              "- **raw**: quran-p2g with its defaults.",
              "- **scorer conventions**: quran-p2g run with the scorer's conventions (closed edges, no basmala item, "
              "no repeat items, a word passes when its phones are any of its legal forms; DESIGN.md section 11).",
              "- **up to ties**: a word that still disagrees counts as agreeing when quran-p2g's segmentation of the "
              "hypothesis costs exactly the scorer's own optimum under the scorer's own cost (unit edit distance "
              "over its lattice), so the scorer's cost cannot tell the two attributions apart.", "",
              "| model | tier | clips | ref words | WER undiacritized | WER diacritized | agreement raw | "
              "scorer conventions | up to ties |", "|---|---|---|---|---|---|---|---|---|"]
        names = {"agg18k": "TajweedFormer V4 (AGG 18k)", "v31": "zipformer v3.1"}
        for m, ms in g3["models"].items():
            for t, v in ms.items():
                a = v["agreement"]
                L.append(f"| {names.get(m, m)} | {t} | {v['rows']:,} | {v['ref_words']:,} | "
                         f"{v['wer_undiacritized_imlaei']:.2f} % | {v['wer_diacritized_uthmani']:.2f} % | "
                         f"{a['agree_pct']:.2f} % ({a['agree']:,} / {a['words']:,}) | "
                         f"{a['agree_convention_pct']:.2f} % | {a['agree_convention_ties_pct']:.2f} % |")
        kinds = {"wasl_edge": "b", "repeat_item": "b", "path_legality": "b", "basmala_item": "b",
                 "tie_in_scorer_cost": "a", "tie_in_p2g_cost": "a", "differs": "c?"}
        L += ["", "Every disagreement by class (raw: disagrees with quran-p2g's defaults; convention only: agrees raw, "
              "disagrees once quran-p2g runs with the scorer's conventions). Kind: (a) an attribution tie, (b) a "
              "convention difference.", "",
              "| model | tier | class | kind | words |", "|---|---|---|---|---|"]
        for m, ms in g3["models"].items():
            for t, v in ms.items():
                for c, n in sorted(v["agreement"]["disagreement_classes"].items(), key=lambda x: (x[0], -x[1])):
                    L.append(f"| {names.get(m, m)} | {t} | {c} | {kinds.get(c.split(':')[-1], '?')} | {n} |")
        L += ["", "- `wasl_edge` (b): quran-p2g accepts the last word running into the next ayah (or the first "
              "continuing the previous one) in wasl; the scorer's lattice has ibtida and waqf edges only.",
              "- `repeat_item` (b): quran-p2g reports repeated material as an inserted repeat and leaves the words "
              "around it a match; the scorer absorbs it into a neighbouring word and flags that word.",
              "- `path_legality` (b): the scorer passes a word whose phones are a legal form in some boundary state, "
              "even when that state does not agree with its neighbour (فَإِذَا with its waqf long vowel, then "
              "ٱنشَقَّتِ in wasl); quran-p2g requires the reading to be one legal path and flags it.",
              "- `tie_in_scorer_cost` (a): the scorer's own cost gives quran-p2g's attribution exactly the scorer's "
              "optimum; the two differ only in which equally cheap path the scorer's backtrace picks (one error at "
              "a word boundary, a truncated clip whose leftover tokens the scorer spreads over the deleted words).",
              ""]
    if g4:
        c, h = g4["canonical_all_ayat"], g4.get("agg18k_t1p_panel_correct_test")
        L += ["## G4 retrieval (no ayah given)", "",
              "| query set | queries | top-1 exact ayah | top-1 up to identical text | top-1 range contains it | "
              "up to identical text, or a range that contains it |",
              "|---|---|---|---|---|---|",
              f"| canonical phones of every ayah | {c['queries']:,} | {c['top1_strict_pct']:.2f} % | "
              f"{c['top1_same_text_pct']:.2f} % | {c['top1_contains_pct']:.2f} % | "
              f"{c['top1_same_text_or_range_pct']:.2f} % |"]
        if h:
            L.append(f"| AGG 18k hypotheses, t1p_panel_correct_test | {h['queries']:,} | {h['top1_strict_pct']:.2f} %"
                     f" | {h['top1_same_text_pct']:.2f} % | {h['top1_contains_pct']:.2f} % | "
                     f"{h['top1_same_text_or_range_pct']:.2f} % |")
        grp = g4["identical_text_groups"]
        dup = sum(int(k) * v for k, v in grp.items() if int(k) > 1)
        ngrp = sum(v for k, v in grp.items() if int(k) > 1)
        ceil = g4["canonical_strict_ceiling"]
        L += ["", f"The exact-ayah column on the canonical set is at its ceiling. {dup} ayat share their folded "
              f"phone string with at least one other ayah, in {ngrp} groups (sizes "
              f"{', '.join(k for k in grp if int(k) > 1)}; the largest is the 31 occurrences of فَبِأَىِّ ءَالَآءِ "
              "رَبِّكُمَا تُكَذِّبَانِ). Identical phones are one query, so whatever a retriever answers, it can be "
              "exactly right for at most one ayah of each group: at most "
              f"{ceil['answerable_exactly']:,} of {ceil['ayat']:,} ayat ({ceil['pct']:.2f} %) can be named "
              f"exactly from phones alone, and quran-p2g names {c['top1_strict']:,}. Every query is answered up to "
              "identical text. On the hypothesis set, one clip labelled with one ayah runs into the next one and "
              "is identified as the range it covers.", ""]
    if mu:
        L += ["## Muaalem script round trip", "",
              "`quran_transcript`'s own phonetizer (the script obadx muaalem models are trained on), run on its "
              "own Uthmani text with Hafs settings, for every ayah, converted with `fmt=\"muaalem\"`.", "",
              "| check | result |", "|---|---|",
              f"| ayat converted with every word a match and the mushaf text | {mu['all_words_match']:,} / "
              f"{mu['ayat']:,} ({pct(mu['all_words_match'], mu['ayat'])}) |",
              f"| ayat whose script maps to exactly quran-g2p's canonical tj3 | {mu['tokens_equal_canonical']:,} / "
              f"{mu['ayat']:,} |",
              f"| residual ayat (the two engines read a word differently) | {mu['residual_ayat']} |", "",
              "Most frequent residual words (said by quran_transcript / expected by quran-g2p):", "",
              "| quran_transcript | quran-g2p lattice form | words |", "|---|---|---|"]
        for a, b, n in mu["residual_word_pairs_said_vs_expected"][:12]:
            L.append(f"| `{a}` | `{b}` | {n} |")
        L.append("")
    g5 = load("g5.json")
    if g5:
        why = {"shadda": "a doubled consonant (shadda is a mark, not a letter)",
               "tanween": "a tanween's noon (tanween is a mark, not a letter)",
               "written_noon": "a written noon sakin or tanween said openly (same letters)",
               "ta_marbuta": "ha / ta of a word written with ta marbuta",
               "seat_fold": "hamza seats and alef maqsura folded by the board's normalisation",
               "OTHER": "a real snap"}
        L += ["## G5 no snapping (tools/gate_g5.py, no ayah given)", "",
              f"{g5['ayat']:,} ayat, canonical reading, one edit per case. Part A: one sound changed; a case is counted "
              "when the WER charges an error. Every case that is not counted is classified by why the written text "
              "cannot show it; the gate passes only with no real snap.", "",
              "| edit | cases | counted | not counted, by reason |", "|---|---|---|---|"]
        for k, v in g5["A_one_sound"].items():
            nc = "; ".join(f"{why.get(x.split(':', 1)[1], x)}: {n}" for x, n in sorted(v.items())
                           if x.startswith("not_counted:"))
            L.append(f"| {k} | {v['cases']:,} | {v['counted']:,} ({pct(v['counted'], v['cases'])}) | {nc or 'none'} |")
        L += ["", f"Real snaps: **{len(g5['A_other_cases'])}**.", "",
              "Part B: the same one-word mistake put into the text a text model would write and into the phones a "
              "phoneme model would write, both through the same WER.", "",
              "| edit | cases | text model WER | phones through quran-p2g WER |", "|---|---|---|---|"]
        for k, v in g5["B_one_word"].items():
            L.append(f"| {k} | {v['cases']:,} | {v['text_wer']:.2f} % | {v['phones_wer']:.2f} % |")
        for k, v in (g5.get("C_several") or {}).items():
            L.append(f"| {k} (several mistakes together) | {v['cases']:,} | {v['text_wer']:.2f} % | {v['phones_wer']:.2f} % |")
        L.append("")
    open(os.path.join(ROOT, "docs", "GATES.md"), "w", encoding="utf-8").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
